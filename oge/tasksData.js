// Шкала перевода первичных баллов в оценку по математике ОГЭ 2025/2026
function calculateGrade(totalPoints, geometryPoints) {
  const geometryFailed = geometryPoints < 2;

  let grade = 2;
  let status = "Не сдал";
  let gradeColor = "red";
  let description = "";

  if (geometryFailed && totalPoints >= 8) {
    grade = 2;
    status = "Ловушка геометрии!";
    gradeColor = "amber";
    description = `Набрано ${totalPoints} баллов, но по геометрии только ${geometryPoints}/2. По правилам ФИПИ выставляется оценка 2!`;
    return { grade, status, gradeColor, description, geometryFailed: true };
  }

  if (totalPoints <= 7) {
    grade = 2;
    status = "Не сдал (Двойка)";
    gradeColor = "red";
    description = "Порог сдачи экзамена не преодолен (нужно от 8 баллов, в т.ч. 2 по геометрии).";
  } else if (totalPoints <= 14) {
    grade = 3;
    status = "Удовлетворительно (Тройка)";
    gradeColor = "yellow";
    description = "Экзамен сдан! Минимальный порог преодолен.";
  } else if (totalPoints <= 21) {
    grade = 4;
    status = "Хорошо (Четверка)";
    gradeColor = "emerald";
    description = "Отличный результат! Уверенный уровень знаний.";
  } else {
    grade = 5;
    status = "Отлично (Пятерка)";
    gradeColor = "purple";
    description = "Великолепный результат! Высший балл ОГЭ.";
  }

  return {
    grade,
    status,
    gradeColor,
    description,
    geometryFailed: false
  };
}

